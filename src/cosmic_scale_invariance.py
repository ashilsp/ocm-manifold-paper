def calculate_depletion_void_radius(mass_kg: float, kappa_flux_factor: float = 1.0) -> float:
    """Estimates mechanical sweep depletion void radius generated by an active UMBH node."""
    if mass_kg <= 0:
        raise ValueError("Mass must be positive.")
    rg = (G * mass_kg) / (C**2)
    # Sweep radius scales with Rd (3 * rg) and kappa-flux pressure projection
    return 3.0 * rg * 10.0 * kappa_flux_factor
