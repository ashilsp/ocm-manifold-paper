import numpy as np

# Physical Constants
G = 6.67430e-11  # m^3 kg^-1 s^-2
C = 2.99792458e8  # m/s
PLANCK_LENGTH = 1.616255e-35  # m
PLANCK_TIME = 5.391247e-44  # s
LY_TO_METER = 9.4607304725808e15  # m

# Cosmological Parameters
R_OBS = 4.4e26  # m (~ 46.5 Gly observable radius)
T_UNIV_SEC = 13.8e9 * 365.25 * 86400.0  # ~ 13.8 billion years in seconds


def calculate_ocm_scaling_constant(
    r_obs: float = R_OBS, l_p: float = PLANCK_LENGTH
) -> float:
    """Computes logarithmic scaling constant zeta_OCM = ln(V_horizon / V_P) = 3 * ln(R_obs / l_p)."""
    if r_obs <= 0 or l_p <= 0:
        raise ValueError("Volumes/lengths must be strictly positive.")

    # Volume ratio simplifies to 3 * ln(R_obs / l_p)
    return float(3.0 * np.log(r_obs / l_p))


def calculate_horizon_scale_limit(
    t_univ_sec: float = T_UNIV_SEC, zeta_ocm: float = 612.0
) -> float:
    """Computes theoretical maximum structural limit L_max = (c * t_univ) / zeta_ocm in light-years."""
    if t_univ_sec <= 0 or zeta_ocm <= 0:
        raise ValueError("Time and scaling constant must be strictly positive.")

    l_max_meters = (C * t_univ_sec) / zeta_ocm
    return float(l_max_meters / LY_TO_METER)


